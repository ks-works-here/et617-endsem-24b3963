/* eslint-disable @typescript-eslint/no-require-imports */
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { chromium } = require(process.env.OPTICS_PLAYWRIGHT || "playwright");

async function main() {
  const browser = await chromium.launch({
    ...(process.env.OPTICS_CHROME ? { executablePath: process.env.OPTICS_CHROME } : {}),
  });
  try {
    const base = process.env.OPTICS_URL || "http://127.0.0.1:3000";
    const page = await browser.newPage({ acceptDownloads: true });
    page.setDefaultTimeout(9000);
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    const click = name => page.getByRole("button", { name, exact: true }).click();
    const visible = text => page.getByText(text, { exact: true }).waitFor();
    const read = key => page.evaluate(key => JSON.parse(localStorage.getItem("optics." + key) || "null"), key);
    await page.goto(base);
    await page.getByRole("link", { name: "Open investigation →" }).click();
    await click("Start investigation");
    await page.getByLabel("Initial hypothesis").fill("I expect a real image even inside the focal length.");
    await click("Explore apparatus");
    await page.getByLabel("Lens type").selectOption("concave");
    await page.getByLabel("Lens type").selectOption("convex");
    const set = async (label, value) => {
      const field = page.getByLabel(label + " in centimetres");
      await field.fill(String(value));
      await field.press("Enter");
    };
    await set("Focal length magnitude", 21);
    await set("Focal length magnitude", 20);
    await set("Object height", 6);
    await click("Prepare experiment");
    await page.getByLabel("Predicted outcome").selectOption("real");
    await click("Run Experiment");
    await set("Screen position", 55);
    await visible("The screen stays unfocused at every position.");
    assert.equal(await page.getByRole("button", { name: "Open explanation" }).isDisabled(), true);
    for (let i = 0; i < 4; i++) await click("Next hint");
    await visible("If you extend the diverging rays backwards, where do they appear to originate?");
    await page.getByLabel("Interpretation").fill("The rays diverge and only their backward extensions meet.");
    await click("Open explanation");
    await page.getByLabel("Hypothesis", { exact: true }).fill("Moving outside F will form a real image.");
    await click("Save revised hypothesis");
    await click("Pause investigation");
    await page.reload();
    await click("Resume Investigation");
    assert.equal((await read("lab")).hints, 4);
    await set("Object distance", 40);
    await set("Screen position", 40);
    await page.getByLabel("Predicted outcome").selectOption("real");
    await click("Run Experiment");
    await visible("Screen aligned. A sharp image is projected.");
    const trials = await read("experiments");
    assert.equal(trials.length, 2);
    assert.equal(trials[0].supported, false);
    assert.match(trials[0].revision, /outside F/);
    assert.equal(trials[1].supported, true);
    await click("Go to reflection");
    await page.getByLabel("Transfer response").fill("The +12 cm lens projects a sharp image because 24 cm is outside F.");
    await page.getByLabel("What did your trials demonstrate?").fill("Inside F gave a virtual image and outside F gave a real image.");
    await click("Complete investigation");
    await page.getByRole("link", { name: "Try the related Olympiad question →" }).click();
    await page.getByRole("heading", { name: "The elusive screen image" }).waitFor();
    await page.getByLabel("Your explanation").fill("Because the lens flips the picture.");
    await click("Submit Answer");
    await click("Weak Area Revision");
    await click("End challenge");
    await page.getByRole("button", { name: /The elusive screen image/ }).click();
    await page.getByLabel("Your explanation").fill("The rays diverge, their backward extensions meet, and the eye focuses the light itself.");
    await click("Submit Answer");
    await click("Bookmark");
    await click("Next hint (0/2)");
    await click("Show Solution");
    await visible("Worked solution");
    assert.equal(await page.locator(".question-list button").count(), 30);
    await page.getByLabel("Category", { exact: false }).selectOption("2");
    await page.getByLabel("Difficulty", { exact: false }).selectOption("0");
    assert.equal(await page.locator(".question-list button").count(), 2);
    await page.getByRole("button", { name: /Complete the construction/ }).click();
    await page.getByRole("img", { name: "Partial ray diagram for a convex lens" }).waitFor();
    await page.getByText("Draw a straight ray from the object tip through the optical centre", { exact: true }).click();
    await click("Submit Answer");
    assert.equal((await read("arena")).records.r1.solved, true);
    await page.getByLabel("Category", { exact: false }).selectOption("0");
    await page.getByLabel("Difficulty", { exact: false }).selectOption("1");
    await page.getByRole("button", { name: /Bright blur at F/ }).click();
    await page.getByText("Both are true and the reason explains the assertion", { exact: true }).click();
    await click("Submit Answer");
    assert.equal((await read("arena")).records.c3.solved, true);
    await page.getByLabel("Category", { exact: false }).selectOption("-1");
    await page.getByLabel("Difficulty", { exact: false }).selectOption("-1");
    await page.getByRole("button", { name: /An inverted fiducial/ }).click();
    await page.getByLabel("Signed v").fill("-20 cm");
    await page.getByLabel("Signed image height").fill("-2 cm");
    await click("Submit Answer");
    await visible("Signed v: check the Cartesian sign or image orientation.");
    await page.getByLabel("Signed v").fill("20 m");
    await click("Submit Answer");
    await visible("Signed v: give your answer in cm.");
    await page.getByLabel("Signed v").fill("60/7 cm");
    await click("Submit Answer");
    await visible("Signed v: check the formula, especially the sign between the reciprocal terms.");
    await page.getByLabel("Signed v").fill("23 cm");
    await click("Submit Answer");
    await visible("Signed v: check the substituted values, reciprocal arithmetic, and rounding.");
    await page.getByLabel("Signed v").fill("20 cm");
    await click("Submit Answer");
    assert.equal((await read("arena")).records.n1.solved, true);
    await click("Mixed Challenge");
    await click("Next question / skip");
    await page.reload();
    assert.equal((await read("arena")).challenge.index, 1);
    await click("End challenge");
    await click("Timed Challenge");
    assert.ok((await read("arena")).challenge.deadline > Date.now());
    await page.evaluate(() => {
      const state = JSON.parse(localStorage.getItem("optics.arena"));
      state.challenge.deadline = Date.now() - 1000;
      localStorage.setItem("optics.arena", JSON.stringify(state));
    });
    await page.reload();
    await page.getByText(/Challenge complete/).waitFor();
    assert.equal((await read("arena")).records.c1.marked, true);
    await page.getByRole("link", { name: "Analytics", exact: true }).click();
    await page.getByLabel("Filter activity").selectOption("Olympiad Arena");
    await page.getByText(/olympiad answer submitted/).first().waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    const events = await read("events");
    assert.equal(new Set(events.map(e => e.event_id)).size, events.length);
    assert.equal(events.filter(e => e.event_type === "session_completed").length, 1);
    const exportFiles = [];
    for (const label of ["Export CSV", "Export JSON", "Export experiments"]) {
      const incoming = page.waitForEvent("download");
      await click(label);
      const downloaded = await incoming;
      assert.equal(await downloaded.failure(), null);
      exportFiles.push(await fs.readFile(await downloaded.path(), "utf8"));
    }
    assert.match(exportFiles[0], /^event_id,session_id,learner_id,timestamp,event_type/);
    assert.ok(exportFiles[0].includes(events[0].event_id));
    assert.deepEqual(JSON.parse(exportFiles[1]).slice(0, events.length), events);
    assert.deepEqual(JSON.parse(exportFiles[2]), trials);
    await page.reload();
    await page.getByRole("heading", { name: "Export history" }).waitFor();
    const logs = await read("exports");
    assert.equal(logs.length, 3);
    assert.equal(logs[0].records, events.length);
    assert.equal(logs[1].records, events.length + 1);
    assert.equal(logs[2].records, trials.length);
    assert.deepEqual(errors, []);
    const evidence = { events: events.filter(row => ["experiment_unsuccessful", "hypothesis_revised", "olympiad_answer_submitted"].includes(row.event_type) && row.details.correct !== false), export: logs[0] };
    if (process.env.OPTICS_EVIDENCE) await fs.writeFile(path.resolve(process.env.OPTICS_EVIDENCE), JSON.stringify(evidence, null, 2));
    console.log("Browser smoke test passed: investigations, persistence, Arena, analytics, and downloaded records.");
  } finally {
    await browser.close();
  }
}

main().catch(error => { console.error(error); process.exitCode = 1; });
